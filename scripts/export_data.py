"""
Export the parquet tables in data/ into a lightweight `data.js` file
consumed by the static viewer (index.html).

The heavy `dips_execution` column is never loaded (it accounts for almost
the entire size of run_table.parquet), so the export stays fast and small.

Usage (from the repository root):
    python scripts/export_data.py
"""

import json
import math
import os

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
DATA_DIR = os.path.join(os.path.dirname(HERE), "data")
RUNS_PATH = os.path.join(DATA_DIR, "run_table.parquet")
ERRORS_PATH = os.path.join(DATA_DIR, "error_table.parquet")
OUT_PATH = os.path.join(os.path.dirname(HERE), "docs", "data.js")

# ---------------------------------------------------------------------------
# Column mapping: parquet column name -> key used in data.js / app.js.
# If the parquet columns are renamed, only the left-hand side must change.
# ---------------------------------------------------------------------------
RUN_COLUMNS = {
    "run_id": "run_id",
    "model_name": "model_name",
    "model_size": "model_size",
    "technique": "technique",
    "context_id": "context_id",
    "prompt_type": "prompt_type",
    "recall": "recall",
    "precision": "precision",
    "jaccard": "jaccard",
    "f1_score": "f1",
    "exact_match": "exact_match",
    "execution_time_s": "time_s",
    "dips_outcome": "dips_outcome",
    "dips_error": "dips_error",
    "jaccard_dips": "jaccard_dips",
    "intent": "intent",
    "generated_output": "generated",
    "gold_output": "gold",
    "total_errors": "n_errors",
    "high_severity_errors": "n_high",
    "low_severity_errors": "n_low",
}

ERROR_COLUMNS = {
    "run_id": "run_id",
    "error_type": "type",
    "error_subtype": "subtype",
    "error_severity": "severity",
}


def clean(value):
    """Convert pandas/numpy scalars into JSON-serialisable Python values."""
    if value is None or value is pd.NA:
        return None
    if isinstance(value, float) and math.isnan(value):
        return None
    if hasattr(value, "item"):  # numpy scalar
        value = value.item()
        if isinstance(value, float) and math.isnan(value):
            return None
    return value


def main():
    runs = pd.read_parquet(RUNS_PATH, columns=list(RUN_COLUMNS))
    runs = runs.rename(columns=RUN_COLUMNS)

    errors = pd.read_parquet(ERRORS_PATH, columns=list(ERROR_COLUMNS))
    errors = errors.rename(columns=ERROR_COLUMNS)

    # Group identical errors of the same run -> (type, subtype, severity, count)
    grouped = (
        errors.groupby(["run_id", "type", "subtype", "severity"], dropna=False)
        .size()
        .reset_index(name="count")
        .sort_values(["run_id", "type", "subtype", "severity"])
    )
    errors_by_run = {}
    for row in grouped.itertuples(index=False):
        errors_by_run.setdefault(row.run_id, []).append(
            [clean(row.type), clean(row.subtype), clean(row.severity), int(row.count)]
        )

    records = []
    for rec in runs.to_dict(orient="records"):
        rec = {k: clean(v) for k, v in rec.items()}
        # Exclude identifier errors missed by the fact comparison.
        rec["exact_match"] = int(rec["exact_match"] == 1 and rec["dips_error"] is not True)
        rec["model_key"] = f"{rec['model_name']}_{rec['model_size']}"
        rec["errors"] = errors_by_run.get(rec["run_id"], [])
        records.append(rec)

    records.sort(
        key=lambda r: (r["model_key"], r["technique"], r["context_id"], r["prompt_type"])
    )

    payload = {"runs": records}
    with open(OUT_PATH, "w", encoding="utf-8") as fh:
        fh.write("// Auto-generated by export_data.py - do not edit by hand.\n")
        fh.write("window.IBN_DATA = ")
        json.dump(payload, fh, ensure_ascii=False, separators=(",", ":"))
        fh.write(";\n")

    size_mb = os.path.getsize(OUT_PATH) / 1_048_576
    print(f"Exported {len(records)} runs, {len(errors)} errors -> {OUT_PATH} ({size_mb:.1f} MB)")


if __name__ == "__main__":
    main()
